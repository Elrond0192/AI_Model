DO $normalize_nationalities$
DECLARE
    tbl record;
    col record;
    changed bigint;
    total_changed bigint := 0;
BEGIN
    -- Correct the authoritative source rows first, including second nationality.
    FOR tbl IN
        SELECT c.relname
        FROM pg_catalog.pg_class c
        JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'Anagrafiche'
          AND c.relkind IN ('r', 'p')
    LOOP
        FOR col IN
            SELECT a.attname
            FROM pg_catalog.pg_attribute a
            JOIN pg_catalog.pg_class c ON c.oid = a.attrelid
            JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
            JOIN pg_catalog.pg_type typ ON typ.oid = a.atttypid
            WHERE n.nspname = 'Anagrafiche'
              AND c.relname = tbl.relname
              AND a.attnum > 0
              AND NOT a.attisdropped
              AND lower(a.attname) IN ('nat', 'nat2', 'nationality', 'nationality2')
              AND typ.typcategory = 'S'
        LOOP
            EXECUTE format(
                'UPDATE %I.%I AS src
                    SET %I = map.alpha2
                   FROM pg_temp._hm_nationality_alpha2_map AS map
                  WHERE upper(btrim(src.%I::text)) = map.code',
                'Anagrafiche', tbl.relname, col.attname, col.attname
            );
            GET DIAGNOSTICS changed = ROW_COUNT;
            total_changed := total_changed + changed;
        END LOOP;
    END LOOP;

    -- Keep the already-materialized AI player registry immediately consistent.
    IF to_regclass('"AI_Source"."Players"') IS NOT NULL THEN
        UPDATE "AI_Source"."Players" AS p
           SET nationality = map.alpha2
          FROM pg_temp._hm_nationality_alpha2_map AS map
         WHERE upper(btrim(p.nationality::text)) = map.code;
        GET DIAGNOSTICS changed = ROW_COUNT;
        total_changed := total_changed + changed;
    END IF;

    RAISE NOTICE 'Nationality codes normalized to ISO alpha-2; rows updated: %', total_changed;
END;
$normalize_nationalities$;

COMMIT;
